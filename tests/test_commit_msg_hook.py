"""The commit-msg hook keeps assistants' signatures out of commit messages (CLAUDE.md,
"Commits"): their trailers, session links and "generated with" lines go, the rest stays."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

HOOK = Path(__file__).resolve().parent.parent / "scripts" / "hooks" / "commit-msg"


def cleaned(tmp_path: Path, message: str) -> str:
    file = tmp_path / "COMMIT_EDITMSG"
    file.write_text(message, encoding="utf-8")
    subprocess.run([sys.executable, str(HOOK), str(file)], check=True)
    return file.read_text(encoding="utf-8")


def test_an_assistants_signature_is_removed(tmp_path: Path) -> None:
    message = (
        "Fix the ferry\n\nThe rope is cut clean through.\n\n"
        "Co-Authored-By: Claude Fable 5.2 <noreply@anthropic.com>\n"
        "Claude-Session: https://claude.ai/code/session_01ABC\n\n"
        "\U0001f916 Generated with [Claude Code](https://claude.com/claude-code)\n\n"
        "https://claude.ai/code/session_01ABC\n"
    )
    assert cleaned(tmp_path, message) == "Fix the ferry\n\nThe rope is cut clean through.\n"


def test_a_person_and_the_authors_own_words_stay(tmp_path: Path) -> None:
    message = (
        "Claude drafts the naming styles of a world\n\n"
        "Names generated by Claude are marked as drafts until the gamemaster takes them.\n\n"
        "Co-Authored-By: Maren Holt <maren@example.org>\n"
    )
    assert cleaned(tmp_path, message) == message


def test_a_message_without_any_is_left_alone(tmp_path: Path) -> None:
    assert cleaned(tmp_path, "Fix the ferry\n") == "Fix the ferry\n"


def test_the_hook_can_run() -> None:
    """Git only runs a hook it may execute."""
    assert HOOK.stat().st_mode & 0o100


def _hook_module() -> object:
    import importlib.util
    from importlib.machinery import SourceFileLoader

    loader = SourceFileLoader("commit_msg", str(HOOK))
    spec = importlib.util.spec_from_loader("commit_msg", loader)
    assert spec is not None
    module = importlib.util.module_from_spec(spec)
    loader.exec_module(module)
    return module


def test_news_is_asked_for_when_the_app_changes() -> None:
    hook = _hook_module()
    remind = hook.news_reminder  # type: ignore[attr-defined]
    plain = "Tracker sorts by initiative\n\nBecause ties broke oddly.\n"
    assert "No News: trailer" in remind(plain, ["app/services/combat.py"])
    assert remind(plain, ["tests/test_combat.py", "documentation/COMBAT.md"]) == ""
    told = plain + "\nNews: The tracker sorts ties by Dexterity.\n"
    assert "News-de" in remind(told, ["app/services/combat.py"])
    both = told + "News-de: Der Tracker ordnet Gleichstände nach Geschicklichkeit.\n"
    assert remind(both, ["app/services/combat.py"]) == ""
    # A News: line in git's comment block does not count.
    assert "No News" in remind(plain + "# News: x\n", ["static/js/ui.js"])


def test_the_reminder_never_refuses_a_commit(tmp_path: Path) -> None:
    file = tmp_path / "COMMIT_EDITMSG"
    file.write_text("Anything\n", encoding="utf-8")
    done = subprocess.run([sys.executable, str(HOOK), str(file)], capture_output=True)
    assert done.returncode == 0
